const ALL: readonly (BoardTemplate | SingleTemplate)[] = [...BOARD_TEMPLATES, ...SINGLE_TEMPLATES];

/** The template with this id, or null. */
export function templateById(id: string): BoardTemplate | SingleTemplate | null {
  return ALL.find((t) => t.id === id) ?? null;
}

/** Every `icon:` value the templates use, sorted and unique. */
export function templateIconNames(): string[] {
  const names = new Set<string>();
  for (const t of ALL) for (const text of "frames" in t ? t.frames : [t.text]) for (const m of text.matchAll(/\bicon: ([a-z0-9-]+)/g)) names.add(m[1]);
  return [...names].sort();
}
