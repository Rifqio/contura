const er = (name: string, ...lines: string[]): SingleTemplate => ({ id: `er-${slug(name)}`, name, kind: "er", text: frame(`diagram er "${name}"`, ...lines) });
const flow = (name: string, ...lines: string[]): SingleTemplate => ({ id: `flow-${slug(name)}`, name, kind: "flow", text: frame(`diagram flow "${name}"`, ...lines) });
const cloud = (name: string, ...lines: string[]): SingleTemplate => ({ id: `cloud-${slug(name)}`, name, kind: "cloud", text: frame(`diagram cloud "${name}"`, ...lines) });
const sequence = (name: string, ...lines: string[]): SingleTemplate => ({
  id: `sequence-${slug(name)}`,
  name,
  kind: "sequence",
  text: frame(`diagram sequence "${name}"`, ...lines),
});
const other = (kind: DiagramKind, name: string, ...lines: string[]): SingleTemplate => ({ id: `${kind}-${slug(name)}`, name, kind, text: frame(`diagram ${kind} "${name}"`, ...lines) });

