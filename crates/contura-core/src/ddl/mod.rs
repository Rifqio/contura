    #[test]
    fn postgres_enums_become_types_and_sqlite_checks() {
        let mut m = neutral_model(DialectKind::Postgres);
        m.enums.push(SmEnum {
            schema: None,
            name: "order_status".into(),
            values: vec!["new".into(), "done".into()],
        });
        m.tables[0].columns[2].type_name = "order_status".into();
        let out = create_script_dated(&m, "2026-10-16").unwrap();
        assert!(
            out.contains("CREATE TYPE \"order_status\" AS ENUM ('new', 'done');"),
            "{out}"
        );
        m.dialect = DialectKind::Sqlite;
        let out = create_script_dated(&m, "2026-10-16").unwrap();
        assert!(
            out.contains("\"status\" TEXT CHECK (\"status\" IN ('new', 'done')) DEFAULT 'new'"),
            "{out}"
        );
    }
