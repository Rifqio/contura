//! Writes a CREATE script for a Schema Model in its own Dialect.

mod mysql;

use crate::design::MySqlColumn;
use crate::error::{Error, Result};
use crate::model::DialectKind;
use crate::schema_model::{SchemaModel, SmColumn, SmDefault, SmEnum, SmRef, SmTable};

pub fn create_script(model: &SchemaModel) -> Result<String> {
    create_script_dated(model, &crate::dbml_writer::today_utc())
}

/// A text literal for DDL, such as a comment.
pub(crate) fn lit(kind: DialectKind, s: &str) -> String {
    match kind {
        // DDL keeps the backslash-doubling literal; the hex form is for edits,
        // and MySQL does not take it after COMMENT.
        DialectKind::MySql => mysql::string_lit(s),
        kind => crate::common::sql_string(kind, s),
    }
}

/// One column definition. `type_sql`, `default_sql` and `mysql.on_update` are
/// SQL text put in as they are: callers check typed text with `check_fragment`.
/// Text the designer loaded and sends back unchanged (D1), such as an unchanged
/// column's type or `mysql.on_update`, is not checked here: Apply refuses
/// unless the loaded design still matches the server (S14).
pub(crate) struct ColumnSql {
    pub name: String,
    pub type_sql: String,
    pub nullable: bool,
    pub default_sql: Option<String>,
    pub increment: bool,
    /// SQLite: write `AUTOINCREMENT` after the rowid alias (ids never reused).
    /// Without it an SQLite increment is the plain rowid alias.
    pub sqlite_autoincrement: bool,
    pub primary_inline: bool,
    pub unique_inline: bool,
    /// Written on MySQL only; the other Dialects use `COMMENT ON` or nothing.
    pub comment: Option<String>,
    pub mysql: Option<MySqlColumn>,
    /// `COLLATE <name>` right after the type. On MySQL `mysql.collation`, when
    /// present, is written instead, so the clause is never written twice.
    pub collation: Option<String>,
    /// Write `NULL` for a nullable column. A MySQL restatement needs it: with
    /// `explicit_defaults_for_timestamp` off a bare `timestamp` turns NOT NULL.
    pub explicit_null: bool,
}

/// `COLLATE <name>`, the name quoted as the Dialect needs.
fn collate_sql(kind: DialectKind, name: &str) -> String {
    match kind {
        DialectKind::MySql => format!("COLLATE {}", mysql::charset_name(name)),
        kind => format!("COLLATE {}", crate::common::sql_ident(kind, name)),
    }
}

/// A column line without its indent, such as `"id" integer NOT NULL`.
/// On SQLite an increment is written as `INTEGER PRIMARY KEY`, plus `AUTOINCREMENT`
/// when `sqlite_autoincrement` is set, in place of the type, so the caller must
/// have checked it is the key.
pub(crate) fn column_sql(kind: DialectKind, c: &ColumnSql) -> String {
    let mut parts = vec![crate::common::sql_ident(kind, &c.name)];
    let sqlite_increment = kind == DialectKind::Sqlite && c.increment;
    if sqlite_increment {
        parts.push(if c.sqlite_autoincrement {
            "INTEGER PRIMARY KEY AUTOINCREMENT".into()
        } else {
            "INTEGER PRIMARY KEY".into()
        });
        if let Some(co) = &c.collation {
            parts.push(collate_sql(kind, co));
        }
    } else {
        // SQLite takes a column without a type.
        if !c.type_sql.is_empty() {
            parts.push(c.type_sql.clone());
        }
        let mut collation = c.collation.as_ref();
        if let (Some(m), DialectKind::MySql) = (&c.mysql, kind) {
            if let Some(cs) = &m.charset {
                parts.push(format!("CHARACTER SET {}", mysql::charset_name(cs)));
            }
            if let Some(co) = &m.collation {
                collation = Some(co);
            }
        }
        if let Some(co) = collation {
            parts.push(collate_sql(kind, co));
        }
        if c.increment {
            parts.push(
                match kind {
                    DialectKind::MySql => "AUTO_INCREMENT",
                    _ => "GENERATED BY DEFAULT AS IDENTITY",
                }
                .into(),
            );
        }
        if c.primary_inline {
            parts.push("PRIMARY KEY".into());
        }
    }
    if !c.nullable && !c.primary_inline && !sqlite_increment {
        parts.push("NOT NULL".into());
    } else if c.nullable && c.explicit_null {
        parts.push("NULL".into());
    }
    if c.unique_inline {
        parts.push("UNIQUE".into());
    }
    if let Some(d) = &c.default_sql {
        if kind == DialectKind::Sqlite {
            parts.push(format!(
                "DEFAULT {}",
                crate::sqlite::tokens::default_clause(d)
            ));
        } else {
            parts.push(format!("DEFAULT {d}"));
        }
    }
    if kind == DialectKind::MySql {
        if let Some(u) = c.mysql.as_ref().and_then(|m| m.on_update.as_ref()) {
            parts.push(format!("ON UPDATE {u}"));
        }
        if let Some(n) = &c.comment {
            parts.push(format!("COMMENT {}", lit(kind, n)));
        }
    }
    parts.join(" ")
}

/// One Foreign Key. `target` is the referenced table as SQL, already quoted;
/// the actions are SQL keywords the caller has checked.
pub(crate) struct FkSql {
    /// Written as `CONSTRAINT <name>` when present.
    pub name: Option<String>,
    pub columns: Vec<String>,
    pub target: String,
    pub target_columns: Vec<String>,
    pub on_delete: Option<String>,
    pub on_update: Option<String>,
}

pub(crate) fn idents(kind: DialectKind, names: &[String]) -> String {
    names
        .iter()
        .map(|c| crate::common::sql_ident(kind, c))
        .collect::<Vec<_>>()
        .join(", ")
}

/// `[CONSTRAINT n] FOREIGN KEY (..) REFERENCES t (..) [ON DELETE a] [ON UPDATE a]`.
pub(crate) fn foreign_key_sql(kind: DialectKind, k: &FkSql) -> String {
    let mut s = String::new();
    if let Some(n) = &k.name {
        s.push_str(&format!(
            "CONSTRAINT {} ",
            crate::common::sql_ident(kind, n)
        ));
    }
    s.push_str(&format!(
        "FOREIGN KEY ({}) REFERENCES {} ({})",
        idents(kind, &k.columns),
        k.target,
        idents(kind, &k.target_columns)
    ));
    if let Some(a) = &k.on_delete {
        s.push_str(&format!(" ON DELETE {a}"));
    }
    if let Some(a) = &k.on_update {
        s.push_str(&format!(" ON UPDATE {a}"));
    }
    s
}

/// A typed default as SQL text in `kind`.
pub(crate) fn default_sql(kind: DialectKind, d: &SmDefault) -> String {
    match d {
        SmDefault::String { value } => lit(kind, value),
        SmDefault::Number { value } => value.clone(),
        SmDefault::Bool { value } => if *value { "TRUE" } else { "FALSE" }.to_string(),
        SmDefault::Null => "NULL".to_string(),
        SmDefault::Expression { value } => {
            if kind == DialectKind::Postgres || is_current_time(value) {
                value.clone()
            } else {
                format!("({value})")
            }
        }
    }
}

struct Writer<'a> {
    model: &'a SchemaModel,
}

impl Writer<'_> {
    fn d(&self) -> DialectKind {
        self.model.dialect
    }

    fn q(&self, name: &str) -> String {
        crate::common::sql_ident(self.d(), name)
    }

    fn lit(&self, s: &str) -> String {
        lit(self.d(), s)
    }

    /// SQLite has one schema per file, so its names are never qualified.
    fn qualified(&self, schema: &Option<String>, name: &str) -> String {
        match (schema, self.d()) {
            (Some(s), DialectKind::MySql | DialectKind::Postgres) => {
                format!("{}.{}", self.q(s), self.q(name))
            }
            _ => self.q(name),
        }
    }

    fn cols(&self, cols: &[String]) -> String {
        cols.iter()
            .map(|c| self.q(c))
            .collect::<Vec<_>>()
            .join(", ")
    }

    fn enum_for(&self, type_name: &str) -> Option<&SmEnum> {
        self.model.enums.iter().find(|e| {
            e.name.eq_ignore_ascii_case(type_name)
                || e.schema
                    .as_deref()
                    .is_some_and(|s| format!("{s}.{}", e.name).eq_ignore_ascii_case(type_name))
        })
    }

    fn enum_values(&self, e: &SmEnum) -> String {
        e.values
            .iter()
            .map(|v| self.lit(v))
            .collect::<Vec<_>>()
            .join(", ")
    }

    fn default_sql(&self, d: &SmDefault) -> String {
        default_sql(self.d(), d)
    }

    fn column(&self, t: &SmTable, c: &SmColumn, single_pk: bool) -> Result<String> {
        if self.d() == DialectKind::Sqlite && c.increment {
            let integer_pk = c.pk && single_pk && c.type_name.eq_ignore_ascii_case("integer");
            if !integer_pk {
                return Err(Error::InvalidInput(format!(
                    "SQLite can only auto-increment a single INTEGER primary key ({}.{})",
                    t.name, c.name
                )));
            }
        }
        let type_sql = match (self.enum_for(&c.type_name), self.d()) {
            (Some(e), DialectKind::MySql) => format!("ENUM({})", self.enum_values(e)),
            (Some(e), DialectKind::Sqlite) => format!(
                "TEXT CHECK ({} IN ({}))",
                self.q(&c.name),
                self.enum_values(e)
            ),
            _ => c.type_name.clone(),
        };
        Ok(column_sql(
            self.d(),
            &ColumnSql {
                name: c.name.clone(),
                type_sql,
                nullable: !c.not_null,
                default_sql: c.default.as_ref().map(|d| self.default_sql(d)),
                increment: c.increment,
                // A Schema Model increment on SQLite has always meant AUTOINCREMENT.
                sqlite_autoincrement: true,
                primary_inline: c.pk,
                unique_inline: c.unique,
                comment: c.note.clone(),
                mysql: None,
                collation: None,
                explicit_null: false,
            },
        ))
    }

    fn foreign_key(&self, r: &SmRef) -> String {
        foreign_key_sql(
            self.d(),
            &FkSql {
                name: None,
                columns: r.from.columns.clone(),
                target: self.qualified(&r.to.schema, &r.to.table),
                target_columns: r.to.columns.clone(),
                on_delete: r.on_delete.clone(),
                on_update: r.on_update.clone(),
            },
        )
    }
}

fn is_current_time(expr: &str) -> bool {
    let e = expr.trim().to_ascii_uppercase();
    let base = e.split('(').next().unwrap_or("");
    matches!(
        base,
        "CURRENT_TIMESTAMP" | "CURRENT_DATE" | "CURRENT_TIME" | "NOW" | "LOCALTIMESTAMP"
    ) && (e == base || e.ends_with(')'))
}

fn same_table(t: &SmTable, schema: &Option<String>, name: &str) -> bool {
    t.name == name && (t.schema == *schema || schema.is_none() || t.schema.is_none())
}

/// Tables in dependency order: a referenced table comes before the tables that
/// reference it. Tables in a cycle keep model order.
fn table_order(model: &SchemaModel) -> Vec<usize> {
    let n = model.tables.len();
    let mut placed = vec![false; n];
    let mut order = Vec::with_capacity(n);
    loop {
        let next = (0..n).find(|&i| {
            !placed[i]
                && model.refs.iter().all(|r| {
                    let t = &model.tables[i];
                    if !same_table(t, &r.from.schema, &r.from.table)
                        || same_table(t, &r.to.schema, &r.to.table)
                    {
                        return true;
                    }
                    (0..n).all(|j| {
                        placed[j] || !same_table(&model.tables[j], &r.to.schema, &r.to.table)
                    })
                })
        });
        match next {
            Some(i) => {
                placed[i] = true;
                order.push(i);
            }
            None => break,
        }
    }
    order.extend((0..n).filter(|&i| !placed[i]));
    order
}

pub(crate) fn create_script_dated(model: &SchemaModel, date: &str) -> Result<String> {
    let w = Writer { model };
    let mut stmts: Vec<String> = Vec::new();

    if model.dialect == DialectKind::Postgres {
        for e in &model.enums {
            stmts.push(format!(
                "CREATE TYPE {} AS ENUM ({});",
                w.qualified(&e.schema, &e.name),
                w.enum_values(e)
            ));
        }
    }

    let order = table_order(model);
    let position = |schema: &Option<String>, name: &str| {
        order
            .iter()
            .position(|&i| same_table(&model.tables[i], schema, name))
    };
    let mut deferred = Vec::new();
    let mut indexes = Vec::new();
    for (pos, &i) in order.iter().enumerate() {
        let t = &model.tables[i];
        let table = w.qualified(&t.schema, &t.name);
        let single_pk = t.columns.iter().filter(|c| c.pk).count() == 1;
        let mut lines = Vec::new();
        for c in &t.columns {
            lines.push(format!("  {}", w.column(t, c, single_pk)?));
        }
        for idx in t.indexes.iter().filter(|x| x.pk) {
            lines.push(format!("  PRIMARY KEY ({})", w.cols(&idx.columns)));
        }
        for r in model
            .refs
            .iter()
            .filter(|r| same_table(t, &r.from.schema, &r.from.table))
        {
            let later = position(&r.to.schema, &r.to.table).is_some_and(|p| p > pos);
            if later && model.dialect != DialectKind::Sqlite {
                deferred.push(format!("ALTER TABLE {table} ADD {};", w.foreign_key(r)));
            } else {
                lines.push(format!("  {}", w.foreign_key(r)));
            }
        }
        let tail = match (&t.note, model.dialect) {
            (Some(n), DialectKind::MySql) => format!(" COMMENT={}", w.lit(n)),
            _ => String::new(),
        };
        stmts.push(format!(
            "CREATE TABLE {table} (\n{}\n){tail};",
            lines.join(",\n")
        ));
        if model.dialect == DialectKind::Postgres {
            if let Some(n) = &t.note {
                stmts.push(format!("COMMENT ON TABLE {table} IS {};", w.lit(n)));
            }
            for c in &t.columns {
                if let Some(n) = &c.note {
                    stmts.push(format!(
                        "COMMENT ON COLUMN {table}.{} IS {};",
                        w.q(&c.name),
                        w.lit(n)
                    ));
                }
            }
        }
        for idx in t.indexes.iter().filter(|x| !x.pk) {
            let name = idx
                .name
                .clone()
                .unwrap_or_else(|| format!("{}_{}_idx", t.name, idx.columns.join("_")));
            indexes.push(format!(
                "CREATE {}INDEX {} ON {table} ({});",
                if idx.unique { "UNIQUE " } else { "" },
                w.q(&name),
                w.cols(&idx.columns)
            ));
        }
    }
    stmts.extend(deferred);
    stmts.extend(indexes);

    Ok(format!(
        "-- Generated by Contura from a Schema Model on {date}\n\n{}\n",
        stmts.join("\n\n")
    ))
}

