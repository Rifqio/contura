    #[test]
    fn export_quotes_odd_names() {
        let mut m = neutral_model(DialectKind::MySql);
        m.tables[1].name = "we`ird name".into();
        m.refs[0].to.table = "we`ird name".into();
        let out = create_script_dated(&m, "2026-10-16").unwrap();
        assert!(out.contains("CREATE TABLE `we``ird name` ("), "{out}");
        assert!(out.contains("REFERENCES `we``ird name` (`id`)"), "{out}");
        let mut p = neutral_model(DialectKind::Postgres);
        p.tables[1].name = "we\"ird ñame".into();
        p.refs[0].to.table = "we\"ird ñame".into();
        let out = create_script_dated(&p, "2026-10-16").unwrap();
        assert!(out.contains("CREATE TABLE \"we\"\"ird ñame\" ("), "{out}");
    }

    #[test]
    fn mysql_column_restates_charset_collation_and_on_update() {
        let c = ColumnSql {
            name: "updated_at".into(),
            type_sql: "varchar(20)".into(),
            nullable: true,
            default_sql: Some("CURRENT_TIMESTAMP".into()),
            increment: false,
            sqlite_autoincrement: false,
            primary_inline: false,
            unique_inline: false,
            comment: Some("a\\b".into()),
            mysql: Some(MySqlColumn {
                charset: Some("utf8mb4".into()),
                collation: Some("odd name".into()),
                on_update: Some("CURRENT_TIMESTAMP".into()),
            }),
            collation: Some("ignored on MySQL when mysql has one".into()),
            explicit_null: false,
        };
        assert_eq!(
            column_sql(DialectKind::MySql, &c),
            "`updated_at` varchar(20) CHARACTER SET utf8mb4 COLLATE `odd name` DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT 'a\\\\b'"
        );
        assert_eq!(
            column_sql(DialectKind::Postgres, &c),
            "\"updated_at\" varchar(20) COLLATE \"ignored on MySQL when mysql has one\" DEFAULT CURRENT_TIMESTAMP"
        );
    }

    #[test]
    fn column_collation_is_written_after_the_type() {
        let c = ColumnSql {
            name: "code".into(),
            type_sql: "text".into(),
            nullable: false,
            default_sql: None,
            increment: false,
            sqlite_autoincrement: false,
            primary_inline: false,
            unique_inline: false,
            comment: None,
            mysql: None,
            collation: Some("C".into()),
            explicit_null: false,
        };
        assert_eq!(
            column_sql(DialectKind::Postgres, &c),
            "\"code\" text COLLATE \"C\" NOT NULL"
        );
        assert_eq!(
            column_sql(DialectKind::Sqlite, &c),
            "\"code\" text COLLATE \"C\" NOT NULL"
        );
        let c = ColumnSql {
            collation: Some("utf8mb4_bin".into()),
            ..c
        };
        assert_eq!(
            column_sql(DialectKind::MySql, &c),
            "`code` text COLLATE utf8mb4_bin NOT NULL"
        );
        let c = ColumnSql {
            collation: Some("x\"y".into()),
            ..c
        };
        assert_eq!(
            column_sql(DialectKind::Postgres, &c),
            "\"code\" text COLLATE \"x\"\"y\" NOT NULL"
        );
    }

