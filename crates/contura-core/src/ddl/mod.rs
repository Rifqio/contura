//! Writes a CREATE script for a Schema Model in its own Dialect.

mod mysql;

use crate::error::{Error, Result};
use crate::model::DialectKind;
use crate::schema_model::{SchemaModel, SmColumn, SmDefault, SmEnum, SmRef, SmTable};

pub fn create_script(model: &SchemaModel) -> Result<String> {
    create_script_dated(model, &crate::dbml_writer::today_utc())
}

struct Writer<'a> {
    model: &'a SchemaModel,
}

impl Writer<'_> {
    fn d(&self) -> DialectKind {
        self.model.dialect
    }

    fn q(&self, name: &str) -> String {
        crate::common::sql_ident(self.d(), name)
    }

    fn lit(&self, s: &str) -> String {
        match self.d() {
            // DDL keeps the backslash-doubling literal; the hex form is for edits.
            DialectKind::MySql => mysql::string_lit(s),
            kind => crate::common::sql_string(kind, s),
        }
    }

    /// SQLite has one schema per file, so its names are never qualified.
    fn qualified(&self, schema: &Option<String>, name: &str) -> String {
        match (schema, self.d()) {
            (Some(s), DialectKind::MySql | DialectKind::Postgres) => {
                format!("{}.{}", self.q(s), self.q(name))
            }
            _ => self.q(name),
        }
    }

    fn cols(&self, cols: &[String]) -> String {
        cols.iter()
            .map(|c| self.q(c))
            .collect::<Vec<_>>()
            .join(", ")
    }

    fn enum_for(&self, type_name: &str) -> Option<&SmEnum> {
        self.model.enums.iter().find(|e| {
            e.name.eq_ignore_ascii_case(type_name)
                || e.schema
                    .as_deref()
                    .is_some_and(|s| format!("{s}.{}", e.name).eq_ignore_ascii_case(type_name))
        })
    }

    fn enum_values(&self, e: &SmEnum) -> String {
        e.values
            .iter()
            .map(|v| self.lit(v))
            .collect::<Vec<_>>()
            .join(", ")
    }

    fn default_sql(&self, d: &SmDefault) -> String {
        match d {
            SmDefault::String { value } => self.lit(value),
            SmDefault::Number { value } => value.clone(),
            SmDefault::Bool { value } => if *value { "TRUE" } else { "FALSE" }.to_string(),
            SmDefault::Null => "NULL".to_string(),
            SmDefault::Expression { value } => {
                let bare = matches!(self.d(), DialectKind::Postgres) || is_current_time(value);
                if bare {
                    value.clone()
                } else {
                    format!("({value})")
                }
            }
        }
    }

    fn column(&self, t: &SmTable, c: &SmColumn, single_pk: bool) -> Result<String> {
        let mut parts = vec![self.q(&c.name)];
        let sqlite = self.d() == DialectKind::Sqlite;
        if sqlite && c.increment {
            let integer_pk = c.pk && single_pk && c.type_name.eq_ignore_ascii_case("integer");
            if !integer_pk {
                return Err(Error::InvalidInput(format!(
                    "SQLite can only auto-increment a single INTEGER primary key ({}.{})",
                    t.name, c.name
                )));
            }
            parts.push("INTEGER PRIMARY KEY AUTOINCREMENT".into());
        } else {
            match (self.enum_for(&c.type_name), self.d()) {
                (Some(e), DialectKind::MySql) => {
                    parts.push(format!("ENUM({})", self.enum_values(e)));
                }
                (Some(e), DialectKind::Sqlite) => parts.push(format!(
                    "TEXT CHECK ({} IN ({}))",
                    self.q(&c.name),
                    self.enum_values(e)
                )),
                _ => parts.push(c.type_name.clone()),
            }
            if c.increment {
                parts.push(
                    match self.d() {
                        DialectKind::MySql => "AUTO_INCREMENT",
                        _ => "GENERATED BY DEFAULT AS IDENTITY",
                    }
                    .into(),
                );
            }
            if c.pk {
                parts.push("PRIMARY KEY".into());
            }
        }
        if c.not_null && !c.pk {
            parts.push("NOT NULL".into());
        }
        if c.unique {
            parts.push("UNIQUE".into());
        }
        if let Some(d) = &c.default {
            parts.push(format!("DEFAULT {}", self.default_sql(d)));
        }
        if let (Some(n), DialectKind::MySql) = (&c.note, self.d()) {
            parts.push(format!("COMMENT {}", self.lit(n)));
        }
        Ok(parts.join(" "))
    }

    fn foreign_key(&self, r: &SmRef) -> String {
        let mut s = format!(
            "FOREIGN KEY ({}) REFERENCES {} ({})",
            self.cols(&r.from.columns),
            self.qualified(&r.to.schema, &r.to.table),
            self.cols(&r.to.columns)
        );
        if let Some(a) = &r.on_delete {
            s.push_str(&format!(" ON DELETE {a}"));
        }
        if let Some(a) = &r.on_update {
            s.push_str(&format!(" ON UPDATE {a}"));
        }
        s
    }
}

fn is_current_time(expr: &str) -> bool {
    let e = expr.trim().to_ascii_uppercase();
    let base = e.split('(').next().unwrap_or("");
    matches!(
        base,
        "CURRENT_TIMESTAMP" | "CURRENT_DATE" | "CURRENT_TIME" | "NOW" | "LOCALTIMESTAMP"
    ) && (e == base || e.ends_with(')'))
}

fn same_table(t: &SmTable, schema: &Option<String>, name: &str) -> bool {
    t.name == name && (t.schema == *schema || schema.is_none() || t.schema.is_none())
}

/// Tables in dependency order: a referenced table comes before the tables that
/// reference it. Tables in a cycle keep model order.
fn table_order(model: &SchemaModel) -> Vec<usize> {
    let n = model.tables.len();
    let mut placed = vec![false; n];
    let mut order = Vec::with_capacity(n);
    loop {
        let next = (0..n).find(|&i| {
            !placed[i]
                && model.refs.iter().all(|r| {
                    let t = &model.tables[i];
                    if !same_table(t, &r.from.schema, &r.from.table)
                        || same_table(t, &r.to.schema, &r.to.table)
                    {
                        return true;
                    }
                    (0..n).all(|j| {
                        placed[j] || !same_table(&model.tables[j], &r.to.schema, &r.to.table)
                    })
                })
        });
        match next {
            Some(i) => {
                placed[i] = true;
                order.push(i);
            }
            None => break,
        }
    }
    order.extend((0..n).filter(|&i| !placed[i]));
    order
}

pub(crate) fn create_script_dated(model: &SchemaModel, date: &str) -> Result<String> {
    let w = Writer { model };
    let mut stmts: Vec<String> = Vec::new();

    if model.dialect == DialectKind::Postgres {
        for e in &model.enums {
            stmts.push(format!(
                "CREATE TYPE {} AS ENUM ({});",
                w.qualified(&e.schema, &e.name),
                w.enum_values(e)
            ));
        }
    }

    let order = table_order(model);
    let position = |schema: &Option<String>, name: &str| {
        order
            .iter()
            .position(|&i| same_table(&model.tables[i], schema, name))
    };
    let mut deferred = Vec::new();
    let mut indexes = Vec::new();
    for (pos, &i) in order.iter().enumerate() {
        let t = &model.tables[i];
        let table = w.qualified(&t.schema, &t.name);
        let single_pk = t.columns.iter().filter(|c| c.pk).count() == 1;
        let mut lines = Vec::new();
        for c in &t.columns {
            lines.push(format!("  {}", w.column(t, c, single_pk)?));
        }
        for idx in t.indexes.iter().filter(|x| x.pk) {
            lines.push(format!("  PRIMARY KEY ({})", w.cols(&idx.columns)));
        }
        for r in model
            .refs
            .iter()
            .filter(|r| same_table(t, &r.from.schema, &r.from.table))
        {
            let later = position(&r.to.schema, &r.to.table).is_some_and(|p| p > pos);
            if later && model.dialect != DialectKind::Sqlite {
                deferred.push(format!("ALTER TABLE {table} ADD {};", w.foreign_key(r)));
            } else {
                lines.push(format!("  {}", w.foreign_key(r)));
            }
        }
        let tail = match (&t.note, model.dialect) {
            (Some(n), DialectKind::MySql) => format!(" COMMENT={}", w.lit(n)),
            _ => String::new(),
        };
        stmts.push(format!(
            "CREATE TABLE {table} (\n{}\n){tail};",
            lines.join(",\n")
        ));
        if model.dialect == DialectKind::Postgres {
            if let Some(n) = &t.note {
                stmts.push(format!("COMMENT ON TABLE {table} IS {};", w.lit(n)));
            }
            for c in &t.columns {
                if let Some(n) = &c.note {
                    stmts.push(format!(
                        "COMMENT ON COLUMN {table}.{} IS {};",
                        w.q(&c.name),
                        w.lit(n)
                    ));
                }
            }
        }
        for idx in t.indexes.iter().filter(|x| !x.pk) {
            let name = idx
                .name
                .clone()
                .unwrap_or_else(|| format!("{}_{}_idx", t.name, idx.columns.join("_")));
            indexes.push(format!(
                "CREATE {}INDEX {} ON {table} ({});",
                if idx.unique { "UNIQUE " } else { "" },
                w.q(&name),
                w.cols(&idx.columns)
            ));
        }
    }
    stmts.extend(deferred);
    stmts.extend(indexes);

    Ok(format!(
        "-- Generated by Contura from a Schema Model on {date}\n\n{}\n",
        stmts.join("\n\n")
    ))
}

#[cfg(test)]
pub(crate) mod tests {
    use super::*;
    use crate::error::Error;
    use crate::model::DialectKind;
    use crate::schema_model::*;

    fn col(name: &str, type_name: &str) -> SmColumn {
        SmColumn {
            name: name.into(),
            type_name: type_name.into(),
            pk: false,
            increment: false,
            not_null: false,
            unique: false,
            default: None,
            note: None,
        }
    }

    fn ep(table: &str, column: &str) -> SmEndpoint {
        SmEndpoint {
            schema: None,
            table: table.into(),
            columns: vec![column.into()],
        }
    }

    /// Types valid in all three Dialects; `orders` comes first so the export must reorder.
    pub(crate) fn neutral_model(dialect: DialectKind) -> SchemaModel {
        let id = SmColumn {
            pk: true,
            increment: true,
            ..col("id", "integer")
        };
        SchemaModel {
            dialect,
            tables: vec![
                SmTable {
                    schema: None,
                    name: "orders".into(),
                    alias: None,
                    note: None,
                    columns: vec![
                        id.clone(),
                        SmColumn {
                            not_null: true,
                            ..col("store_id", "integer")
                        },
                        SmColumn {
                            default: Some(SmDefault::String {
                                value: "new".into(),
                            }),
                            ..col("status", "varchar(10)")
                        },
                    ],
                    indexes: vec![SmIndex {
                        name: Some("ix_store".into()),
                        columns: vec!["store_id".into()],
                        unique: false,
                        pk: false,
                    }],
                },
                SmTable {
                    schema: None,
                    name: "stores".into(),
                    alias: None,
                    note: Some("KFC stores".into()),
                    columns: vec![
                        id,
                        SmColumn {
                            not_null: true,
                            unique: true,
                            note: Some("display name".into()),
                            ..col("name", "varchar(80)")
                        },
                    ],
                    indexes: vec![],
                },
            ],
            refs: vec![SmRef {
                name: None,
                from: ep("orders", "store_id"),
                to: ep("stores", "id"),
                on_delete: Some("CASCADE".into()),
                on_update: None,
            }],
            enums: vec![],
            skipped: vec![],
        }
    }

    const MYSQL: &str = "-- Generated by Contura from a Schema Model on 2026-10-16

CREATE TABLE `stores` (
  `id` integer AUTO_INCREMENT PRIMARY KEY,
  `name` varchar(80) NOT NULL UNIQUE COMMENT 'display name'
) COMMENT='KFC stores';

CREATE TABLE `orders` (
  `id` integer AUTO_INCREMENT PRIMARY KEY,
  `store_id` integer NOT NULL,
  `status` varchar(10) DEFAULT 'new',
  FOREIGN KEY (`store_id`) REFERENCES `stores` (`id`) ON DELETE CASCADE
);

CREATE INDEX `ix_store` ON `orders` (`store_id`);
";

    const POSTGRES: &str = "-- Generated by Contura from a Schema Model on 2026-10-16

CREATE TABLE \"stores\" (
  \"id\" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  \"name\" varchar(80) NOT NULL UNIQUE
);

COMMENT ON TABLE \"stores\" IS 'KFC stores';

COMMENT ON COLUMN \"stores\".\"name\" IS 'display name';

CREATE TABLE \"orders\" (
  \"id\" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  \"store_id\" integer NOT NULL,
  \"status\" varchar(10) DEFAULT 'new',
  FOREIGN KEY (\"store_id\") REFERENCES \"stores\" (\"id\") ON DELETE CASCADE
);

CREATE INDEX \"ix_store\" ON \"orders\" (\"store_id\");
";

    const SQLITE: &str = "-- Generated by Contura from a Schema Model on 2026-10-16

CREATE TABLE \"stores\" (
  \"id\" INTEGER PRIMARY KEY AUTOINCREMENT,
  \"name\" varchar(80) NOT NULL UNIQUE
);

CREATE TABLE \"orders\" (
  \"id\" INTEGER PRIMARY KEY AUTOINCREMENT,
  \"store_id\" integer NOT NULL,
  \"status\" varchar(10) DEFAULT 'new',
  FOREIGN KEY (\"store_id\") REFERENCES \"stores\" (\"id\") ON DELETE CASCADE
);

CREATE INDEX \"ix_store\" ON \"orders\" (\"store_id\");
";

    fn script(d: DialectKind) -> String {
        create_script_dated(&neutral_model(d), "2026-10-16").unwrap()
    }

    #[test]
    fn mysql_script_for_kfc_model() {
        assert_eq!(script(DialectKind::MySql), MYSQL);
    }

    #[test]
    fn postgres_script_for_kfc_model() {
        assert_eq!(script(DialectKind::Postgres), POSTGRES);
    }

    #[test]
    fn sqlite_script_for_kfc_model() {
        assert_eq!(script(DialectKind::Sqlite), SQLITE);
    }

    #[test]
    fn export_quotes_odd_names() {
        let mut m = neutral_model(DialectKind::MySql);
        m.tables[1].name = "we`ird name".into();
        m.refs[0].to.table = "we`ird name".into();
        let out = create_script_dated(&m, "2026-10-16").unwrap();
        assert!(out.contains("CREATE TABLE `we``ird name` ("), "{out}");
        assert!(out.contains("REFERENCES `we``ird name` (`id`)"), "{out}");
        let mut p = neutral_model(DialectKind::Postgres);
        p.tables[1].name = "we\"ird ñame".into();
        p.refs[0].to.table = "we\"ird ñame".into();
        let out = create_script_dated(&p, "2026-10-16").unwrap();
        assert!(out.contains("CREATE TABLE \"we\"\"ird ñame\" ("), "{out}");
    }

    #[test]
    fn cyclic_refs_become_alter_table() {
        let mut m = neutral_model(DialectKind::Postgres);
        m.tables[1].columns.push(col("best_order_id", "integer"));
        m.refs.push(SmRef {
            name: None,
            from: ep("stores", "best_order_id"),
            to: ep("orders", "id"),
            on_delete: None,
            on_update: None,
        });
        let out = create_script_dated(&m, "2026-10-16").unwrap();
        assert!(
            out.contains(
                "ALTER TABLE \"orders\" ADD FOREIGN KEY (\"store_id\") REFERENCES \"stores\" (\"id\") ON DELETE CASCADE;"
            ),
            "{out}"
        );
        assert!(!out.contains("  FOREIGN KEY (\"store_id\")"), "{out}");
    }

    #[test]
    fn sqlite_increment_needs_single_integer_pk() {
        let mut m = neutral_model(DialectKind::Sqlite);
        m.tables[0].columns[1].increment = true;
        let err = create_script_dated(&m, "2026-10-16").unwrap_err();
        assert!(matches!(err, Error::InvalidInput(_)), "{err:?}");
    }

    #[test]
    fn postgres_enums_become_types_and_sqlite_checks() {
        let mut m = neutral_model(DialectKind::Postgres);
        m.enums.push(SmEnum {
            schema: None,
            name: "order_status".into(),
            values: vec!["new".into(), "done".into()],
        });
        m.tables[0].columns[2].type_name = "order_status".into();
        let out = create_script_dated(&m, "2026-10-16").unwrap();
        assert!(
            out.contains("CREATE TYPE \"order_status\" AS ENUM ('new', 'done');"),
            "{out}"
        );
        m.dialect = DialectKind::Sqlite;
        let out = create_script_dated(&m, "2026-10-16").unwrap();
        assert!(
            out.contains("\"status\" TEXT CHECK (\"status\" IN ('new', 'done')) DEFAULT 'new'"),
            "{out}"
        );
    }
}
