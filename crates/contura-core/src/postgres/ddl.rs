//! A table's CREATE statements as the server holds the table (D14): PostgreSQL
//! keeps no CREATE TABLE text, so it is written from the catalog, with the
//! server's own text for every constraint, index and expression.

use tokio_postgres::Client;

use super::query_err;
use crate::common::{quote_double, sql_string};
use crate::error::{Error, Result};
use crate::model::DialectKind;

/// What the text leaves out, said once at its top.
const NOT_SHOWN: &str = "-- Written by Contura from the server's catalog. Triggers, policies, \
     grants, storage parameters and inheritance are not shown.";

const TABLE_SQL: &str = "\
SELECT c.oid, c.relpersistence::text, \
       CASE WHEN c.relkind = 'p' THEN pg_get_partkeydef(c.oid) END, \
       obj_description(c.oid, 'pg_class') \
  FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace \
 WHERE n.nspname = $1 AND c.relname = $2 AND c.relkind IN ('r', 'p')";

const COLUMNS_SQL: &str = "\
SELECT a.attname::text, format_type(a.atttypid, a.atttypmod), a.attnotnull, \
       a.attidentity::text, a.attgenerated::text, pg_get_expr(d.adbin, d.adrelid), \
       CASE WHEN a.attcollation <> 0 AND a.attcollation <> t.typcollation THEN \
         (SELECT format('%I.%I', cn.nspname, co.collname) \
            FROM pg_collation co JOIN pg_namespace cn ON cn.oid = co.collnamespace \
           WHERE co.oid = a.attcollation) END, \
       col_description(a.attrelid, a.attnum) \
  FROM pg_attribute a \
  JOIN pg_type t ON t.oid = a.atttypid \
  LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum \
 WHERE a.attrelid = $1 AND a.attnum > 0 AND NOT a.attisdropped \
 ORDER BY a.attnum";

/// NOT NULL stays on the column (PostgreSQL 18 also lists it as a constraint). A Foreign Key
/// to a partitioned table is written once: its copies on the same table (one per partition
/// of the referenced table) are left out. A partition keeps the copy of its parent's key,
/// so its DDL shows the key it holds.
const CONSTRAINTS_SQL: &str = "\
SELECT conname::text, pg_get_constraintdef(oid, true) \
  FROM pg_constraint \
 WHERE conrelid = $1 AND contype IN ('p', 'u', 'c', 'x', 'f') \
   AND (contype <> 'f' OR conparentid = 0 \
        OR (SELECT p.conrelid FROM pg_constraint p WHERE p.oid = pg_constraint.conparentid) \
           <> pg_constraint.conrelid) \
 ORDER BY CASE contype WHEN 'p' THEN 0 WHEN 'u' THEN 1 WHEN 'c' THEN 2 \
                       WHEN 'x' THEN 3 ELSE 4 END, conname";

/// Indexes no constraint owns; a constraint's index comes with the constraint.
const INDEXES_SQL: &str = "\
SELECT pg_get_indexdef(i.indexrelid) \
  FROM pg_index i JOIN pg_class ic ON ic.oid = i.indexrelid \
 WHERE i.indrelid = $1 \
   AND NOT EXISTS (SELECT 1 FROM pg_constraint k \
                    WHERE k.conindid = i.indexrelid AND k.conrelid = i.indrelid \
                      AND k.contype IN ('p', 'u', 'x')) \
 ORDER BY ic.relname";

fn lit(s: &str) -> String {
    sql_string(DialectKind::Postgres, s)
}

pub(super) async fn table_ddl(client: &Client, schema: &str, name: &str) -> Result<String> {
    let table_row = client
        .query_opt(TABLE_SQL, &[&schema, &name])
        .await
        .map_err(query_err)?
        .ok_or_else(|| Error::NotFound(format!("{name} in {schema}")))?;
    let oid: u32 = table_row.try_get(0).map_err(query_err)?;
    let persistence: String = table_row.try_get(1).map_err(query_err)?;
    let partition: Option<String> = table_row.try_get(2).map_err(query_err)?;
    let comment: Option<String> = table_row.try_get(3).map_err(query_err)?;
    let table = format!("{}.{}", quote_double(schema), quote_double(name));

    let mut lines = Vec::new();
    let mut column_comments = Vec::new();
    for row in client
        .query(COLUMNS_SQL, &[&oid])
        .await
        .map_err(query_err)?
    {
        let column: String = row.try_get(0).map_err(query_err)?;
        let type_sql: String = row.try_get(1).map_err(query_err)?;
        let not_null: bool = row.try_get(2).map_err(query_err)?;
        let identity: String = row.try_get(3).map_err(query_err)?;
        let generated: String = row.try_get(4).map_err(query_err)?;
        let expr: Option<String> = row.try_get(5).map_err(query_err)?;
        let collation: Option<String> = row.try_get(6).map_err(query_err)?;
        let note: Option<String> = row.try_get(7).map_err(query_err)?;
        let mut line = format!("{} {type_sql}", quote_double(&column));
        if let Some(c) = collation {
            line.push_str(&format!(" COLLATE {c}"));
        }
        match (generated.as_str(), identity.as_str(), &expr) {
            ("s", _, Some(e)) => line.push_str(&format!(" GENERATED ALWAYS AS ({e}) STORED")),
            ("v", _, Some(e)) => line.push_str(&format!(" GENERATED ALWAYS AS ({e}) VIRTUAL")),
            (_, "a", _) => line.push_str(" GENERATED ALWAYS AS IDENTITY"),
            (_, "d", _) => line.push_str(" GENERATED BY DEFAULT AS IDENTITY"),
            (_, _, Some(e)) => line.push_str(&format!(" DEFAULT {e}")),
            _ => {}
        }
        if not_null {
            line.push_str(" NOT NULL");
        }
        lines.push(line);
        if let Some(n) = note {
            column_comments.push(format!(
                "COMMENT ON COLUMN {table}.{} IS {};",
                quote_double(&column),
                lit(&n)
            ));
        }
    }
    for row in client
        .query(CONSTRAINTS_SQL, &[&oid])
        .await
        .map_err(query_err)?
    {
        let constraint: String = row.try_get(0).map_err(query_err)?;
        let definition: String = row.try_get(1).map_err(query_err)?;
        lines.push(format!(
            "CONSTRAINT {} {definition}",
            quote_double(&constraint)
        ));
    }

    let unlogged = if persistence == "u" { "UNLOGGED " } else { "" };
    let partition = partition
        .map(|p| format!(" PARTITION BY {p}"))
        .unwrap_or_default();
    let mut out = vec![
        NOT_SHOWN.to_string(),
        format!(
            "CREATE {unlogged}TABLE {table} (\n  {}\n){partition};",
            lines.join(",\n  ")
        ),
    ];
    for row in client
        .query(INDEXES_SQL, &[&oid])
        .await
        .map_err(query_err)?
    {
        let definition: String = row.try_get(0).map_err(query_err)?;
        out.push(format!("{definition};"));
    }
    if let Some(c) = comment {
        out.push(format!("COMMENT ON TABLE {table} IS {};", lit(&c)));
    }
    out.extend(column_comments);
    Ok(out.join("\n\n"))
}
