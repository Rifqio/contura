/// Whether `name` (as `safety::function_calls` gives it) is built into `dialect`. A
/// schema-qualified name is built in only as `pg_catalog.<name>` on Postgres.
pub fn is_builtin(dialect: DialectKind, name: &str) -> bool {
    let name = name.to_lowercase();
    let (list, bare) = match dialect {
        DialectKind::Postgres => (POSTGRES, name.strip_prefix("pg_catalog.").unwrap_or(&name)),
        DialectKind::MySql => (MYSQL, name.as_str()),
        DialectKind::Sqlite => (SQLITE, name.as_str()),
    };
    !bare.contains('.') && list.binary_search(&bare).is_ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn lists_are_sorted_and_lower_case() {
        for list in [POSTGRES, MYSQL, SQLITE] {
            assert!(list.windows(2).all(|w| w[0] < w[1]), "{list:?}");
            assert!(list.iter().all(|n| *n == n.to_lowercase()));
        }
    }

    #[test]
    fn builtins_per_dialect() {
        use DialectKind::{MySql, Postgres, Sqlite};
        assert!(is_builtin(Postgres, "COUNT"));
        assert!(is_builtin(Postgres, "pg_catalog.now"));
        assert!(!is_builtin(Postgres, "public.now"));
        assert!(!is_builtin(MySql, "pg_catalog.now"));
        assert!(is_builtin(MySql, "group_concat"));
        assert!(!is_builtin(Postgres, "group_concat"));
        assert!(is_builtin(Sqlite, "strftime"));
        assert!(!is_builtin(MySql, "strftime"));
        assert!(is_builtin(MySql, "if"));
        assert!(!is_builtin(Postgres, "orders_purge"));
        // time() is read as a call now (F5): built into MySQL and SQLite, a type in Postgres.
        assert!(is_builtin(MySql, "time"));
        assert!(is_builtin(Sqlite, "time"));
        assert!(!is_builtin(Postgres, "time"));
    }
}
