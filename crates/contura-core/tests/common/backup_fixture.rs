/// A connection to `database` as the test user.
pub async fn mysql_conn(db: &TestDb, database: &str) -> Conn {
    let opts: Opts = OptsBuilder::default()
        .ip_or_hostname(db.config.host.clone())
        .tcp_port(db.config.port)
        .user(Some(db.config.user.clone()))
        .pass(db.password.clone())
        .db_name(Some(database.to_string()))
        .into();
    Conn::new(opts).await.expect("connect to test MySQL")
}

pub async fn mysql_fixture(db: &TestDb) {
    let mut conn = mysql_conn(db, &db.name).await;
    for sql in MYSQL_FIXTURE {
        conn.query_drop(*sql)
            .await
            .unwrap_or_else(|e| panic!("{sql}: {e}"));
    }
    conn.disconnect().await.ok();
}

