/// What the round trip adds to the Backup fixture, in order, on one session.
pub fn round_trip_statements(kind: DialectKind, rows: u64) -> Vec<String> {
    let mut out = every_type_statements(kind, PG_SCHEMA, "kinds", rows);
    let extra: &[&str] = match kind {
        DialectKind::MySql => &[
            "CREATE TABLE line_items (order_id INT NOT NULL, line_no INT NOT NULL, \
             note VARCHAR(40) COMMENT 'free text', PRIMARY KEY (order_id, line_no), \
             CONSTRAINT line_items_order FOREIGN KEY (order_id) REFERENCES orders (id)) \
             ENGINE=InnoDB COMMENT='order lines'",
            "INSERT INTO line_items VALUES (1, 1, 'first'), (1, 2, NULL), (2, 1, 'ünï 表 😀')",
            "CREATE TABLE `naïve \"q\" 表` (`größe` INT PRIMARY KEY, `it's` VARCHAR(20)) \
             DEFAULT CHARSET=utf8mb4",
            "INSERT INTO `naïve \"q\" 表` VALUES (1, 'a''b'), (2, NULL)",
            "CREATE TABLE zero_dates (id INT PRIMARY KEY, d DATE NULL, dt DATETIME NULL)",
            "SET SESSION sql_mode = ''",
            "INSERT INTO zero_dates VALUES (1, '0000-00-00', '0000-00-00 00:00:00'), \
             (2, '2026-01-00', '2026-00-01 10:00:00'), (3, '2026-10-19', NULL)",
        ],
        DialectKind::Postgres => &[
            "CREATE TABLE billing.line_items (order_id bigint NOT NULL REFERENCES billing.orders (id), \
             line_no integer NOT NULL, note text, PRIMARY KEY (order_id, line_no))",
            "COMMENT ON COLUMN billing.line_items.note IS 'free text'",
            "INSERT INTO billing.line_items VALUES (1, 1, 'first'), (1, 2, NULL), (2, 1, 'ünï 表 😀')",
            "CREATE TABLE billing.\"naïve \"\"q\"\" 表\" (\"größe\" integer PRIMARY KEY, \"it's\" text)",
            "INSERT INTO billing.\"naïve \"\"q\"\" 表\" VALUES (1, 'a''b'), (2, NULL)",
            "CREATE TABLE billing.edges (id integer PRIMARY KEY, d date, ts timestamp, tz timestamptz)",
            "INSERT INTO billing.edges VALUES (1, 'infinity', '-infinity', 'infinity'), \
             (2, '-infinity', 'infinity', '-infinity'), (3, '2026-10-19', NULL, NULL)",
        ],
        DialectKind::Sqlite => &[
            "CREATE TABLE line_items (order_id INTEGER NOT NULL REFERENCES orders (id), \
             line_no INTEGER NOT NULL, note TEXT, PRIMARY KEY (order_id, line_no)) WITHOUT ROWID",
            "INSERT INTO line_items VALUES (1, 1, 'first'), (1, 2, NULL), (2, 1, 'ünï 表 😀')",
            "CREATE TABLE \"naïve \"\"q\"\" 表\" (\"größe\" INTEGER PRIMARY KEY, \"it's\" TEXT)",
            "INSERT INTO \"naïve \"\"q\"\" 表\" VALUES (1, 'a''b'), (2, NULL)",
        ],
    };
    out.extend(extra.iter().map(|s| s.to_string()));
    out
}

/// The Backup fixture plus the round trip's tables, on `db`.
pub async fn mysql_round_trip_fixture(db: &TestDb, rows: u64) {
    mysql_fixture(db).await;
    let mut conn = mysql_conn(db, &db.name).await;
    for sql in round_trip_statements(DialectKind::MySql, rows) {
        conn.query_drop(&sql)
            .await
            .unwrap_or_else(|e| panic!("{sql}: {e}"));
    }
    conn.disconnect().await.ok();
}

pub async fn pg_round_trip_fixture(db: &PgTestDb, rows: u64) {
    let client = pg_fixture(db).await;
    for sql in round_trip_statements(DialectKind::Postgres, rows) {
        client
            .execute(sql.as_str(), &[])
            .await
            .unwrap_or_else(|e| panic!("{sql}: {e}"));
    }
}

pub fn sqlite_round_trip_fixture(path: &std::path::Path, rows: u64) {
    sqlite_fixture(path);
    let conn = rusqlite::Connection::open(path).expect("open the SQLite fixture");
    for sql in round_trip_statements(DialectKind::Sqlite, rows) {
        conn.execute(&sql, [])
            .unwrap_or_else(|e| panic!("{sql}: {e}"));
    }
}
