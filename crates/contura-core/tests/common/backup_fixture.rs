pub async fn pg_fixture(db: &PgTestDb) -> Client {
    let client = pg_admin_client(&db.name).await;
    for sql in PG_FIXTURE {
        client
            .batch_execute(sql)
            .await
            .unwrap_or_else(|e| panic!("{sql}: {e}"));
    }
    client
}

pub const SQLITE_FIXTURE: &str = "
    CREATE TABLE customers (id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT NOT NULL UNIQUE,
        mood TEXT NOT NULL DEFAULT 'ok' CHECK (mood IN ('ok', 'sad')),
        best_order_id INTEGER REFERENCES orders (id));
    CREATE TABLE orders (id INTEGER PRIMARY KEY, customer_id INTEGER NOT NULL REFERENCES customers (id),
        qty INTEGER NOT NULL CHECK (qty > 0), twice INTEGER GENERATED ALWAYS AS (qty * 2) STORED);
    CREATE TABLE audit (id INTEGER PRIMARY KEY, note TEXT);
    CREATE INDEX orders_qty ON orders (qty);
    CREATE VIEW v_base AS SELECT id, qty FROM orders WHERE qty > 1;
    CREATE VIEW a_top AS SELECT id FROM v_base;
    CREATE TRIGGER orders_audit AFTER INSERT ON orders
        BEGIN INSERT INTO audit (note) VALUES ('order ' || NEW.id); END;
    CREATE VIRTUAL TABLE docs USING fts5(body);
    INSERT INTO customers (name, mood) VALUES ('Ana', 'ok'), ('Budi', 'sad'), ('Citra', 'ok'), ('Dewi', 'ok');
    DELETE FROM customers WHERE name = 'Dewi';
    INSERT INTO orders (customer_id, qty) VALUES (1, 1), (1, 2), (2, 3), (3, 4), (3, 5);
    UPDATE customers SET best_order_id = 2 WHERE id = 1;
    PRAGMA user_version = 7;
";

pub fn sqlite_fixture(path: &std::path::Path) {
    rusqlite::Connection::open(path)
        .expect("create the SQLite fixture")
        .execute_batch(SQLITE_FIXTURE)
        .expect("fill the SQLite fixture");
}

